# 6 · transcript  --  what was said, on the grid
# --------------------------------------------------------------------------

@dataclass
class Transcript:
    """The raw transcript cut to chunks.

    **Chunks with no speech are kept, with empty text.** The grid is shared, so
    `chunk_id` must mean the same thing here as in the manifest; dropping the
    quiet ones renumbers everything after them and breaks that correspondence
    silently.

    Only `speakers` goes into `structured`, never `turns`. For a description
    the structured half is worth embedding because it holds what the summary
    does not; but `turns[].text` *is* the transcript, so rendering it would
    append the whole chunk a second time interleaved with timestamps read as
    numbers. The turns are the record and stay on the chunk.
    """

    video_id: str
    timeline_fingerprint: str = ""
    model: dict[str, Any] = field(default_factory=dict)
    chunks: list[dict[str, Any]] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)

    def text_of(self, chunk_id: int) -> str:
        for chunk in self.chunks:
            if chunk["chunk_id"] == chunk_id:
                return chunk.get("text", "")
        return ""

    def as_dict(self) -> dict[str, Any]:
        return {"document": "transcript", "version": 1,
                "video_id": self.video_id,
                "timeline_fingerprint": self.timeline_fingerprint,
                "model": self.model, "stats": self.stats,
                "chunks": self.chunks}

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Transcript":
        return cls(video_id=d["video_id"],
                   timeline_fingerprint=d.get("timeline_fingerprint", ""),
                   model=d.get("model", {}), chunks=d.get("chunks", []),
                   stats=d.get("stats", {}))


