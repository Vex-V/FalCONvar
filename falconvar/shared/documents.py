"""What every artifact is.

Imports nothing, and that is load-bearing: if a document's dataclass lived in
the component that produces it, `cut` would import `boundaries` to read a
timeline, growing exactly the edges the file-handoff design removes. Every
component imports a shape from here; none imports another.

The split against the components is shape versus derivation --
`Timeline.index_at` is shape, `grid.enforce` is derivation.

These dataclasses are also the source for `db/json/*.schema.json`, generated by
`schemas.py` rather than maintained beside them.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from typing import Any, Optional

#: Rounding for identity and serialisation. Boundaries come from float
#: arithmetic over two independent clocks, so comparing them exactly would
#: report drift that is not there. A millisecond is far finer than any boundary
#: decision this pipeline makes.
PRECISION = 3


def _round(value: Optional[float]) -> Optional[float]:
    return None if value is None else round(value, PRECISION)


def _hash(payload: dict[str, Any]) -> str:
    """A short, stable hash of a document's identifying content.

    `sort_keys` is not cosmetic. `jsonb` preserves array order but not object
    key order -- it stores keys by (length, bytewise) -- so a document read back
    from Postgres hands back its keys in a different order from the file. A
    hash over iteration order would then differ by where the document was read
    from, which is a bug `falconvar` shipped and had to chase down.
    """
    text = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


