@dataclass
class Aggregate:
    """One aggregator's answer about the whole video.

    ``inputs_fingerprint`` is a hash of the chunk text actually read. A summary
    of descriptions that have since been rewritten reads perfectly, which is
    precisely why staleness cannot be left to a reader to notice.
    """

    video_id: str
    aggregate_id: str
    tier: str
    payload: dict[str, Any] = field(default_factory=dict)
    inputs_fingerprint: str = ""
    stats: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return {"document": "aggregate", "version": 1,
                "video_id": self.video_id, "aggregate_id": self.aggregate_id,
                "tier": self.tier, "inputs_fingerprint": self.inputs_fingerprint,
                "payload": self.payload, "stats": self.stats}

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Aggregate":
        return cls(video_id=d["video_id"], aggregate_id=d["aggregate_id"],
                   tier=d.get("tier", "free"), payload=d.get("payload", {}),
                   inputs_fingerprint=d.get("inputs_fingerprint", ""),
                   stats=d.get("stats", {}))


def fingerprint_of(payload: dict[str, Any]) -> str:
    """A stable hash of arbitrary content. Exposed for components that need
    their own staleness key -- `inputs_fingerprint`, `text_hash`."""
    return _hash(payload)


