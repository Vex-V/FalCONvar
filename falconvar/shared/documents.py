@dataclass
class Produced:
    """What a component actually wrote.

    A bare path would be shorter and say less. This reports the real output:
    no ``store`` on a run with the frame store off, no ``transcript`` on a
    silent file, and the stats a progress callback wants -- so a caller learns
    what happened rather than assuming from what it asked for.
    """

    video_id: str
    component: str
    backend: str                                  # "file" | "supabase" | both
    artifacts: dict[str, str] = field(default_factory=dict)
    stats: dict[str, Any] = field(default_factory=dict)
    skipped: list[str] = field(default_factory=list)

    def path(self, name: str) -> str:
        return self.artifacts[name]

    def as_dict(self) -> dict[str, Any]:
        return {"video_id": self.video_id, "component": self.component,
                "backend": self.backend, "artifacts": self.artifacts,
                "stats": self.stats, "skipped": self.skipped}


