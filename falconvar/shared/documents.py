# 2 · raw transcript  --  what was said, before any grid exists
# --------------------------------------------------------------------------

@dataclass
class RawTranscript:
    """Words, segments and speaker turns. **No chunks.**

    Stored before it is cut, and that is the asymmetry the whole ordering
    argument rests on. Whisper timestamps every word, so this can be re-cut to
    any grid, any number of times, without touching a model -- while a
    sampler's decisions are made during a decode pass and cannot be revisited.
    Keeping the ungridded record as a file is what lets a grid change without
    re-running inference; `falconvar` holds it in memory and discards it.

    ``turns`` is empty when no diarizer ran, and every segment then keeps
    ``speaker: None``. A transcript with no speaker information is truthful;
    one where everything is `SPEAKER_00` is not.
    """

    video_id: str
    model: dict[str, Any] = field(default_factory=dict)
    track: dict[str, Any] = field(default_factory=dict)
    segments: list[dict[str, Any]] = field(default_factory=list)
    words: list[dict[str, Any]] = field(default_factory=list)
    turns: list[dict[str, Any]] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)

    @property
    def speakers(self) -> list[str]:
        seen = {t.get("speaker") for t in self.turns}
        return sorted(s for s in seen if s)

    @property
    def silent(self) -> bool:
        return bool(self.track.get("silent", False))

    def as_dict(self) -> dict[str, Any]:
        return {
            "document": "raw_transcript", "version": 1,
            "video_id": self.video_id,
            "model": self.model,
            "track": self.track,
            "speakers": self.speakers,
            "segments": self.segments,
            "words": self.words,
            "turns": self.turns,
            "stats": self.stats,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "RawTranscript":
        return cls(video_id=d["video_id"], model=d.get("model", {}),
                   track=d.get("track", {}), segments=d.get("segments", []),
                   words=d.get("words", []), turns=d.get("turns", []),
                   stats=d.get("stats", {}))


